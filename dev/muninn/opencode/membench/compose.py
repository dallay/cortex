"""Container topology for the benchmark.

The harness renders the Compose file instead of shipping a static one, so the
project name, the image digests, the owner scope, and the secret file are
bound to a single run and can be validated before Docker is invoked.

Topology rules enforced here:

* Neo4j joins only the internal network and publishes no port.
* The runner joins the internal network (to reach Neo4j) and the egress
  network (to reach the model provider).
* No container mounts the host home directory or the Docker socket.
* Every container runs with dropped capabilities and a read-only root
  filesystem.
"""

from __future__ import annotations

import re
import shlex
from dataclasses import dataclass, field
from pathlib import Path
from typing import Sequence

from .errors import BenchError

NEO4J_IMAGE = "neo4j:5.26-community"
OPENCODE_IMAGE = "ghcr.io/anomalyco/opencode:2.2.7"
RUNNER_IMAGE = "membench-opencode-runner:2.2.7"

INTERNAL_NETWORK = "bench_db"
EGRESS_NETWORK = "bench_egress"


@dataclass(frozen=True)
class Limits:
    """Resource limits applied to every container."""

    memory: str = "2g"
    cpus: str = "2.0"
    pids: int = 512

    def render(self) -> list[str]:
        return [
            f"    mem_limit: {self.memory}",
            f"    cpus: {self.cpus}",
            f"    pids_limit: {self.pids}",
        ]


@dataclass(frozen=True)
class Topology:
    """The concrete container topology for one run."""

    project: str
    compose_dir: Path
    run_dir: Path
    scenario_file: Path
    config_dir: Path
    env_file: Path
    neo4j_image: str = NEO4J_IMAGE
    opencode_image: str = OPENCODE_IMAGE
    runner_image: str = RUNNER_IMAGE
    owner_scope: str = "bench-owner"
    embedding_provider: str = "minilm"
    embedding_bundle_path: Path | None = None
    embedding_bundle_id: str | None = None
    embedding_dimensions: int = 384
    limits: Limits = field(default_factory=Limits)

    def compose_file(self) -> Path:
        """Return the path of the generated Compose file.

        The file is written inside the temporary run directory, never inside
        the repository.
        """

        return self.run_dir / "compose.generated.yaml"

    def render(self) -> str:
        """Render the Compose file for this topology."""

        embedding_lines = [
            f"      NAM_EMBEDDING__PROVIDER: {self.embedding_provider}",
            f"      NAM_EMBEDDING__DIMENSIONS: {self.embedding_dimensions}",
        ]
        if self.embedding_bundle_path is not None:
            embedding_lines.append(
                f"      NAM_EMBEDDING__BUNDLE_PATH: /bundle{self.embedding_bundle_path.name}"
            )
        if self.embedding_bundle_id:
            embedding_lines.append(f"      NAM_EMBEDDING__BUNDLE_ID: {self.embedding_bundle_id}")

        bundle_mount = ""
        if self.embedding_bundle_path is not None:
            bundle_mount = (
                f"      - {self.embedding_bundle_path}:/bundle{self.embedding_bundle_path.name}:ro\n"
            )

        neo4j_limits = "\n".join(self.limits.render())
        runner_limits = "\n".join(self.limits.render())

        return f"""# Generated by membench. Do not edit; regenerate with `membench run`.
name: {self.project}

services:
  neo4j:
    image: {self.neo4j_image}
    networks:
      - {INTERNAL_NETWORK}
    restart: "no"
{neo4j_limits}
    cap_drop:
      - ALL
    security_opt:
      - no-new-privileges:true
    tmpfs:
      - /data:size=512m
      - /logs:size=64m
    environment:
      NEO4J_AUTH: neo4j/${{BENCH_NEO4J_PASSWORD}}
      NEO4J_server_memory_heap_max__size: 1G
      NEO4J_server_memory_pagecache_size: 256m
    healthcheck:
      test: ["CMD-SHELL", "wget -qO- http://127.0.0.1:7474/ >/dev/null 2>&1 || exit 1"]
      interval: 5s
      timeout: 5s
      retries: 30

  seed:
    image: {self.runner_image}
    networks:
      - {INTERNAL_NETWORK}
    user: "${{BENCH_UID:-10001}}:${{BENCH_GID:-10001}}"
    depends_on:
      neo4j:
        condition: service_healthy
    entrypoint: ["/bin/sh", "/bench/bin/seed.sh"]
    read_only: true
    tmpfs:
      - /tmp:size=32m
    cap_drop:
      - ALL
    security_opt:
      - no-new-privileges:true
{runner_limits}
    environment:
      NAM_NEO4J__URI: bolt://neo4j:7687
      NAM_NEO4J__USERNAME: neo4j
      NAM_NEO4J__PASSWORD: ${{BENCH_NEO4J_PASSWORD}}
{chr(10).join(embedding_lines)}
      MUNINN_MCP_OWNER_SCOPE: {self.owner_scope}
      BENCH_SCENARIO_FILE: /bench/scenarios/{self.scenario_file.name}
      BENCH_SEED_PLAN: /run-seed/seed-plan.json
    volumes:
      - {self.scenario_file}:/bench/scenarios/{self.scenario_file.name}:ro
      - {self.run_dir}:/run-seed:ro
      - {self.compose_dir}:/bench:ro
{bundle_mount}

  runner:
    image: {self.runner_image}
    networks:
      - {INTERNAL_NETWORK}
      - {EGRESS_NETWORK}
    user: "${{BENCH_UID:-10001}}:${{BENCH_GID:-10001}}"
    depends_on:
      neo4j:
        condition: service_healthy
    entrypoint: ["/bin/sh", "-c", "sleep infinity"]
    read_only: true
    tmpfs:
      - /run:size=512m
      - /tmp:size=64m
    cap_drop:
      - ALL
    security_opt:
      - no-new-privileges:true
{runner_limits}
    environment:
      HOME: /run/home
      OPENCODE_DB: /run/home/opencode.db
      NAM_NEO4J__URI: bolt://neo4j:7687
      NAM_NEO4J__USERNAME: neo4j
      NAM_NEO4J__PASSWORD: ${{BENCH_NEO4J_PASSWORD}}
{chr(10).join(embedding_lines)}
      MUNINN_MCP_OWNER_SCOPE: {self.owner_scope}
      BENCH_AUTH_DIR: /opencode/auth
    volumes:
      - {self.run_dir}:/run-config:ro
      - opencode-auth:/opencode/auth
{bundle_mount}
    healthcheck:
      test: ["CMD", "opencode", "--version"]
      interval: 10s
      timeout: 5s
      retries: 5

networks:
  {INTERNAL_NETWORK}:
    internal: true
  {EGRESS_NETWORK}: {{}}

volumes:
  opencode-auth: {{}}
"""


def validate_rendered(compose_text: str) -> list[str]:
    """Check the rendered Compose file against the topology rules.

    Returns a list of violations; an empty list means the topology is valid.
    """

    violations: list[str] = []
    if "docker.sock" in compose_text:
        violations.append("the Compose file mounts the Docker socket")
    for marker in (
        "$HOME",
        "~/.opencode",
        "~/.config/opencode",
        "~/.local/share/opencode",
    ):
        if marker in compose_text:
            violations.append(f"the Compose file references a host home path: {marker}")
    if re.search(r"/home/[^/\s]+/\.(opencode|config|local)", compose_text):
        violations.append("the Compose file mounts a host configuration directory")
    if "published:" in compose_text or "ports:" in compose_text:
        violations.append("the Compose file publishes a host port")
    if f"{INTERNAL_NETWORK}:\n    internal: true" not in compose_text:
        violations.append("the internal network is not marked internal")
    return violations


def validate(topology: Topology) -> None:
    """Validate a topology before Docker is involved."""

    if not topology.scenario_file.is_file():
        raise BenchError(f"scenario file not found: {topology.scenario_file}")
    if not topology.env_file.is_file():
        raise BenchError(f"secret file not found: {topology.env_file}")
    violations = validate_rendered(topology.render())
    if violations:
        raise BenchError("invalid container topology: " + "; ".join(violations))


def compose_command(topology: Topology, *args: str) -> list[str]:
    """Build a ``docker compose`` command for this topology."""

    return [
        "docker",
        "compose",
        "--project-name",
        topology.project,
        "--file",
        str(topology.compose_file()),
        "--env-file",
        str(topology.env_file),
        *args,
    ]


def quote(values: Sequence[str]) -> str:
    """Render a command for logs."""

    return " ".join(shlex.quote(value) for value in values)
