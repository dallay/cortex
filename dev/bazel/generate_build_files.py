def _inventory_contract() -> Any:
    """Load the checker that owns the portable Cargo package identity."""
    path = Path(__file__).with_name("check_inventory.py")
    spec = importlib.util.spec_from_file_location("check_inventory", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load the inventory checker from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


