def run_cargo_metadata(root: Path = ROOT) -> dict[str, Any]:
    """Return `cargo metadata` for the workspace."""
    try:
        result = subprocess.run(
            ["cargo", "metadata", "--locked", "--no-deps", "--format-version", "1"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError) as error:
        detail = getattr(error, "stderr", "") or str(error)
        raise GeneratorError(f"cargo metadata failed: {detail.strip()}") from error
    try:
        return json.loads(result.stdout)
    except json.JSONDecodeError as error:
        raise GeneratorError(f"cargo metadata returned invalid JSON: {error}") from error


def workspace_packages(metadata: dict[str, Any]) -> list[dict[str, Any]]:
    """Return the workspace member packages, sorted by manifest path."""
    packages = metadata.get("packages")
    members = metadata.get("workspace_members")
    if not isinstance(packages, list) or not isinstance(members, list):
        raise GeneratorError("cargo metadata must contain packages and workspace_members")
    by_id = {str(package.get("id")): package for package in packages}
    selected = [by_id[member] for member in members if member in by_id]
    if len(selected) != len(members):
        raise GeneratorError("cargo metadata lists a workspace member without a package record")
    return sorted(selected, key=lambda package: str(package["manifest_path"]))


def crate_name(name: str) -> str:
    """Return the Rust crate name for a Cargo package or target name."""
    return name.replace("-", "_")


def package_directory(package: dict[str, Any], root: Path = ROOT) -> str:
    """Return the repository relative directory of a package."""
    manifest = Path(str(package["manifest_path"])).resolve()
    try:
        relative = manifest.parent.relative_to(root.resolve())
    except ValueError as error:
        raise GeneratorError(f"package manifest is outside the repository: {manifest}") from error
    return relative.as_posix()


def package_index(packages: list[dict[str, Any]], root: Path = ROOT) -> dict[str, dict[str, Any]]:
    """Map repository relative package directories to their metadata record."""
    return {package_directory(package, root): package for package in packages}


