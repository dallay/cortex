#!/usr/bin/env python3
"""Generate Bazel BUILD files from the Cargo workspace inventory.

The generator reads `cargo metadata --locked --no-deps --format-version 1` and
emits one BUILD.bazel per workspace package. Every Cargo target maps to a Bazel
target:

* the library target becomes a `rust_library`,
* a library with `#[cfg(test)]` modules also gets a `rust_test` unit target,
* every integration test becomes a `rust_test`,
* every binary and example becomes a `rust_binary`,
* a `build.rs` becomes a `cargo_build_script`.

Workspace path dependencies are emitted as explicit `//dir:crate_name` labels
because `all_crate_deps` only resolves registry crates. The generator is
deterministic: the same metadata always produces byte-identical output.

The generator never overwrites a hand-tuned BUILD file. Files that carry the
generated marker are rewritten and verified with `--check`; hand-tuned files are
only compared semantically and reported.
"""

