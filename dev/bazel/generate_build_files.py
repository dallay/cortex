def dependency_kind(dependency: dict[str, Any]) -> str:
    kind = dependency.get("kind")
    return "normal" if kind in (None, "") else str(kind)


def dependency_extern_name(dependency: dict[str, Any]) -> str:
    rename = dependency.get("rename")
    return crate_name(str(rename or dependency["name"]))


def is_path_dependency(dependency: dict[str, Any]) -> bool:
    return bool(dependency.get("path"))


def path_dependency_directory(dependency: dict[str, Any], root: Path) -> str:
    path = Path(str(dependency["path"])).resolve()
    try:
        return path.relative_to(root.resolve()).as_posix()
    except ValueError as error:
        raise GeneratorError(f"path dependency is outside the repository: {path}") from error


def package_dependencies(package: dict[str, Any], kind: str) -> list[dict[str, Any]]:
    dependencies = package.get("dependencies")
    if not isinstance(dependencies, list):
        raise GeneratorError(f"package {package.get('name')} has no dependencies array")
    return [dep for dep in dependencies if dependency_kind(dep) == kind]


def enabled_features(package: dict[str, Any], extra: list[str] | None = None) -> list[str]:
    """Return the feature names Cargo enables for a package.

    The result mirrors Cargo: the `default` feature list is expanded
    transitively, optional dependencies enabled through `dep:<name>` are
    reported separately, and the `default` feature itself is not a cfg name.
    """
    features = package.get("features")
    if not isinstance(features, dict):
        raise GeneratorError(f"package {package.get('name')} has no features map")
    enabled: set[str] = set()
    pending = list(features.get("default", [])) + list(extra or [])
    optional: set[str] = set()
    while pending:
        entry = pending.pop()
        if entry.startswith("dep:"):
            optional.add(entry.removeprefix("dep:"))
            continue
        if "/" in entry:
            dependency, _, feature = entry.partition("/")
            optional.add(dependency)
            continue
        if entry in enabled:
            continue
        enabled.add(entry)
        pending.extend(features.get(entry, []))
    enabled.discard("default")
    return sorted(enabled)


def optional_dependencies_enabled(package: dict[str, Any], extra: list[str] | None = None) -> set[str]:
    """Return optional dependencies enabled by default and extra features."""
    features = package.get("features") or {}
    enabled: set[str] = set()
    visited: set[str] = set()
    pending = list(features.get("default", [])) + list(extra or [])
    while pending:
        entry = pending.pop()
        if entry.startswith("dep:"):
            enabled.add(crate_name(entry.removeprefix("dep:")))
            continue
        if "/" in entry:
            enabled.add(crate_name(entry.partition("/")[0]))
            continue
        if entry in visited:
            continue
        visited.add(entry)
        pending.extend(features.get(entry, []))
    return enabled


def workspace_labels(
    package: dict[str, Any],
    kinds: tuple[str, ...],
    index: dict[str, dict[str, Any]],
    enabled_optional: set[str],
    root: Path = ROOT,
) -> list[str]:
    """Return explicit `//dir:crate_name` labels for workspace path dependencies."""
    labels: list[str] = set()
    for kind in kinds:
        for dependency in package_dependencies(package, kind):
            if not is_path_dependency(dependency):
                continue
            if dependency.get("optional") and dependency_extern_name(dependency) not in enabled_optional:
                continue
            directory = path_dependency_directory(dependency, root)
            owner = index.get(directory)
            if owner is None:
                raise GeneratorError(
                    f"path dependency {dependency['name']} is not a workspace member: {directory}"
                )
            labels.add(f"//{directory}:{crate_name(str(owner['name']))}")
    return sorted(labels)


def deps_expression(workspace: list[str], external: str | None) -> str:
    """Return the Starlark expression for a dependency list."""
    if not workspace and not external:
        return "[]"
    if not workspace:
        return external or "[]"
    rendered = "[" + ", ".join(f'"{label}"' for label in workspace) + "]"
    if not external:
        return rendered
    if len(workspace) == 1:
        return f"{rendered} + {external}"
    return f"{rendered} + {external}"


