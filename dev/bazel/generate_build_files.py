def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--metadata", type=Path, help="Read Cargo metadata JSON instead of running Cargo")
    parser.add_argument("--check", action="store_true", help="Report drift instead of writing files")
    parser.add_argument(
        "--exclude-prefix",
        action="append",
        default=None,
        help="Package directory prefix to skip (repeatable)",
    )
    parser.add_argument(
        "--only",
        action="append",
        default=None,
        help="Package directory to model (repeatable)",
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="Write the generated BUILD files (default when not checking)",
    )
    parser.add_argument(
        "--inventory",
        type=Path,
        help="Write the inventory mapping for the modeled packages to this path",
    )
    return parser.parse_args(argv)


def select_packages(
    packages: list[dict[str, Any]],
    root: Path,
    excluded_prefixes: tuple[str, ...],
    only: list[str] | None,
) -> list[dict[str, Any]]:
    selected: list[dict[str, Any]] = []
    for package in packages:
        directory = package_directory(package, root)
        if only is not None:
            if directory not in only:
                continue
        elif any(directory.startswith(prefix) for prefix in excluded_prefixes):
            continue
        selected.append(package)
    return selected


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    root = args.root.resolve()
    try:
        metadata = json.loads(args.metadata.read_text()) if args.metadata else run_cargo_metadata(root)
        packages = workspace_packages(metadata)
        excluded = tuple(args.exclude_prefix) if args.exclude_prefix else DEFAULT_EXCLUDED_PREFIXES
        selected = select_packages(packages, root, excluded, args.only)
        index = package_index(packages, root)
        plans = [build_plan(package, root, index) for package in selected]
        plans = attach_exports(plans, root)
    except (OSError, json.JSONDecodeError, GeneratorError) as error:
        print(f"generation failed: {error}", file=sys.stderr)
        return 1

    drift: list[str] = []
    handwritten: list[str] = []
    for plan in plans:
        path = root / plan.directory / "BUILD.bazel"
        rendered = render_package(plan)
        if path.is_file():
            current = path.read_text()
            if GENERATED_MARKER in current:
                if current != rendered:
                    if args.check:
                        drift.append(plan.directory)
                    else:
                        path.write_text(rendered)
            else:
                handwritten.append(plan.directory)
                continue
        elif args.check:
            drift.append(plan.directory)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered)

    if args.inventory:
        entries = merge_inventory(args.inventory, plans, root, packages)
        args.inventory.write_text(json.dumps({"entries": entries}, indent=2, sort_keys=True) + "\n")

    if handwritten:
        print(f"Hand-tuned BUILD files kept as-is: {len(handwritten)}")
        for directory in handwritten:
            print(f"  {directory}")
    if drift:
        print(f"Drift detected in {len(drift)} package(s):", file=sys.stderr)
        for directory in drift:
            print(f"  {directory}", file=sys.stderr)
        print(f"Run {REGENERATE_COMMAND} to update.", file=sys.stderr)
        return 1
    if args.check:
        print(f"No drift detected in {len(plans)} generated package(s).")
    return 0


def attach_exports(plans: list[PackagePlan], root: Path) -> list[PackagePlan]:
    """Add `exports_files` entries for files referenced across packages."""
    owners = {plan.directory: plan for plan in plans}
    for plan in plans:
        for foreign in plan.unexportable:
            owner = owning_package_directory(Path(foreign), root)
            if owner and owner in owners:
                relative = Path(foreign).resolve().relative_to((root / owner).resolve()).as_posix()
                owners[owner].exports.append(relative)
    for plan in plans:
        plan.exports = sorted(set(plan.exports))
    return plans


def merge_inventory(
    path: Path,
    plans: list[PackagePlan],
    root: Path,
    all_packages: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Merge modeled entries and retain out-of-scope targets explicitly."""
    existing: list[dict[str, Any]] = []
    if path.is_file():
        try:
            existing = json.loads(path.read_text()).get("entries", [])
        except (OSError, json.JSONDecodeError):
            existing = []
    modeled = {(plan.directory, plan.package_id): plan for plan in plans}
    merged: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str, str]] = set()
    for entry in existing:
        key = (
            str(entry.get("manifest", "")),
            str(entry.get("package_id", "")),
            str(entry.get("target", "")),
            str(entry.get("kinds", "")),
        )
        if key in seen:
            continue
        directory = str(entry.get("manifest", "")).rsplit("/", 1)[0]
        plan = modeled.get((directory, str(entry.get("package_id", ""))))
        if plan is not None:
            continue
        seen.add(key)
        merged.append(entry)
    merged.extend(inventory_entries(plans))
    modeled_directories = {plan.directory for plan in plans}
    for package in all_packages:
        directory = package_directory(package, root)
        if directory in modeled_directories:
            continue
        manifest = f"{directory}/Cargo.toml"
        package_id = portable_package_id(str(package["id"]), directory)
        for cargo_target in package.get("targets", []):
            target_name = str(cargo_target["name"])
            kinds = target_kinds(cargo_target)
            key = (manifest, package_id, target_name, ",".join(kinds))
            if key in seen:
                continue
            existing_entry = next((
                entry for entry in existing
                if inventory_sort_key(entry) == key
            ), None)
            if existing_entry is not None:
                merged.append(existing_entry)
            else:
                merged.append({
                    "manifest": manifest,
                    "package_id": package_id,
                    "target": target_name,
                    "kinds": ",".join(kinds),
                    "exclusion": (
                        "Huginn BUILD targets are owned by a concurrent workstream; "
                        "this target is recorded but not yet independently verified "
                        "by the non-Huginn generator."
                    ),
                })
    return sorted(merged, key=inventory_sort_key)


