def target_kinds(cargo_target: dict[str, Any]) -> tuple[str, ...]:
    kinds = cargo_target.get("kind")
    if not isinstance(kinds, list) or not kinds:
        raise GeneratorError(f"target {cargo_target.get('name')} has no kind")
    return tuple(sorted(str(kind) for kind in kinds))


def library_target(package: dict[str, Any]) -> dict[str, Any] | None:
    for cargo_target in package.get("targets", []):
        kinds = target_kinds(cargo_target)
        if "lib" in kinds or "proc-macro" in kinds or "cdylib" in kinds:
            return cargo_target
    return None


def relative_src_path(cargo_target: dict[str, Any], directory: str, root: Path = ROOT) -> str:
    src = Path(str(cargo_target["src_path"])).resolve()
    return relative_to_package(src, directory, root) or src.name


def feature_slug(features: list[str]) -> str:
    return "_".join(feature.replace("-", "_") for feature in sorted(features))


def build_plan(
    package: dict[str, Any],
    root: Path = ROOT,
    index: dict[str, dict[str, Any]] | None = None,
    exclude_targets: dict[tuple[str, str], str] | None = None,
) -> PackagePlan:
    """Build the Bazel target plan of a Cargo package."""
    index = index if index is not None else {}
    exclusions = exclude_targets if exclude_targets is not None else TARGET_EXCLUSIONS
    directory = package_directory(package, root)
    plan = PackagePlan(directory=directory, package=package)
    plan.exclusions = {
        target_name: reason
        for (excluded_directory, target_name), reason in exclusions.items()
        if excluded_directory == directory
    }
    name = str(package["name"])
    crate = crate_name(name)
    sources = package_source_files(directory, root)
    features = enabled_features(package)
    optional_enabled = optional_dependencies_enabled(package)

    library = library_target(package)
    library_name = crate
    library_sources = [source for source in sources if source.is_relative_to(root / directory / "src")]
    gated = feature_gated_sources(
        Path(str(library["src_path"])).resolve() if library else None,
        library_sources,
        set(features),
    )
    library_sources = [source for source in library_sources if source not in gated]
    compile_data, foreign = compile_data_labels(directory, library_sources, root)
    plan.unexportable = foreign
    compile_data = sorted(set(compile_data) | set(PACKAGE_EXTRA_COMPILE_DATA.get(directory, [])))

    normal_workspace = workspace_labels(package, ("normal",), index, optional_enabled, root)
    dev_workspace = workspace_labels(package, ("dev",), index, optional_enabled, root)
    build_workspace = workspace_labels(package, ("build",), index, optional_enabled, root)

    build_script_target = None
    for cargo_target in package.get("targets", []):
        if "custom-build" in target_kinds(cargo_target):
            build_script_target = cargo_target
            break

    if build_script_target is not None and (directory, str(build_script_target["name"])) not in exclusions:
        build_script_name = "build_script"
        build_deps = deps_expression(build_workspace, "all_crate_deps(build = True, build_proc_macro = True)")
        build_script_attributes: dict[str, Any] = {
            "name": build_script_name,
            "srcs": [relative_src_path(build_script_target, directory, root)],
            "crate_name": "build_script_build",
            "edition": Raw("crate_edition()"),
            "pkg_name": crate_name(name),
            "deps": Raw(build_deps),
            "proc_macro_deps": Raw("all_crate_deps(build_proc_macro = True)"),
            "rustc_env": {"CARGO_PKG_VERSION": str(package.get("version", "0.0.0"))},
        }
        extra_compile_data = PACKAGE_EXTRA_COMPILE_DATA.get(directory, [])
        if extra_compile_data:
            build_script_attributes["data"] = extra_compile_data
        plan.targets.append(TargetPlan(
            name=build_script_name,
            rule="cargo_build_script",
            attributes=build_script_attributes,
            cargo_target=str(build_script_target["name"]),
            kinds=target_kinds(build_script_target),
        ))

    if library is not None and (directory, str(library["name"])) not in exclusions:
        library_deps = deps_expression(normal_workspace, "all_crate_deps(normal = True)")
        if build_script_target is not None and plan.target("build_script") is not None:
            library_deps = deps_expression(normal_workspace + [":build_script"], "all_crate_deps(normal = True)")
        attributes: dict[str, Any] = {
            "name": library_name,
            "srcs": Raw('glob(["src/**/*.rs"])'),
            "crate_name": crate,
            "crate_root": relative_src_path(library, directory, root),
        }
        if compile_data:
            attributes["compile_data"] = compile_data_expression(compile_data)
        if features:
            attributes["crate_features"] = features
        attributes["edition"] = Raw("crate_edition()")
        attributes["deps"] = Raw(library_deps)
        attributes["proc_macro_deps"] = Raw("all_crate_deps(proc_macro = True)")
        plan.targets.append(TargetPlan(
            name=library_name,
            rule="rust_library",
            attributes=attributes,
            cargo_target=str(library["name"]),
            kinds=target_kinds(library),
        ))

        if has_unit_tests(library_sources):
            unit_deps = deps_expression(
                sorted(set(normal_workspace + dev_workspace)),
                "all_crate_deps(normal = True, normal_dev = True)",
            )
            unit_test_name = f"{crate}_unit_test"
            unit_test_attributes: dict[str, Any] = {
                "name": unit_test_name,
                "crate": f":{library_name}",
                "aliases": Raw("aliases(normal_dev = True, proc_macro_dev = True)"),
                "edition": Raw("crate_edition()"),
                "deps": Raw(unit_deps),
                "proc_macro_deps": Raw("all_crate_deps(proc_macro = True, proc_macro_dev = True)"),
            }
            sandbox_tags = sandbox_tags_for(directory, unit_test_name)
            if sandbox_tags:
                unit_test_attributes["tags"] = sandbox_tags
            plan.targets.append(TargetPlan(
                name=unit_test_name,
                rule="rust_test",
                attributes=unit_test_attributes,
                cargo_target=f"{library['name']} (unit tests)",
                kinds=("lib",),
            ))

    used_names = {target_plan.name for target_plan in plan.targets}
    assigned_names: dict[str, str] = {}
    for cargo_target in package.get("targets", []):
        kinds = target_kinds(cargo_target)
        cargo_name = str(cargo_target["name"])
        if (directory, cargo_name) in exclusions:
            continue
        if "custom-build" in kinds:
            continue
        if "lib" in kinds or "proc-macro" in kinds or "cdylib" in kinds:
            continue
        required = [str(feature) for feature in (cargo_target.get("required-features") or [])]
        if required:
            variant_name = f"{crate}_{feature_slug(required)}"
            used_names.add(variant_name)
        candidate = crate_name(cargo_name)
        if candidate in used_names:
            if "bin" in kinds:
                candidate = f"{candidate}_bin"
            elif "test" in kinds:
                candidate = f"{candidate}_test"
            else:
                candidate = f"{candidate}_example"
        assigned_names[cargo_name] = candidate
        used_names.add(candidate)

    for cargo_target in package.get("targets", []):
        kinds = target_kinds(cargo_target)
        cargo_name = str(cargo_target["name"])
        target_src = Path(str(cargo_target["src_path"])).resolve()
        target_sources = binary_source_paths(cargo_target)
        target_compile_data, target_foreign = compile_data_labels(directory, target_sources, root)
        target_compile_data = sorted(
            set(target_compile_data) | set(PACKAGE_EXTRA_COMPILE_DATA.get(directory, []))
        )
        if target_foreign and (directory, cargo_name) not in exclusions:
            exclusions = dict(exclusions)
            references = sorted(
                Path(path).resolve().relative_to(root.resolve()).as_posix()
                for path in target_foreign
                if Path(path).resolve().is_relative_to(root.resolve())
            )
            reason = (
                "The target embeds files that live in the root package "
                f"({', '.join(references)}) and the root BUILD.bazel does not export "
                "them. The root BUILD.bazel is outside this generator's ownership, "
                "so the target is not modeled."
            )
            exclusions[(directory, cargo_name)] = reason
            plan.exclusions[cargo_name] = reason
        if (directory, cargo_name) in exclusions:
            continue
        if "custom-build" in kinds:
            continue
        if "lib" in kinds or "proc-macro" in kinds or "cdylib" in kinds:
            continue
        required = [str(feature) for feature in (cargo_target.get("required-features") or [])]
        variant_name = library_name
        if required:
            variant_name = f"{crate}_{feature_slug(required)}"
            variant_features = sorted(set(features) | set(required))
            variant_optional = optional_dependencies_enabled(package, required)
            variant_workspace = workspace_labels(package, ("normal",), index, variant_optional, root)
            optional_external = sorted(
                f"@crates//{dependency['name']}-{str(dependency['req']).removeprefix('=')}"
                for dependency in package_dependencies(package, "normal")
                if dependency.get("optional")
                and crate_name(str(dependency["name"])) in variant_optional
                and not is_path_dependency(dependency)
                and str(dependency.get("req", "")).startswith("=")
            )
            variant_deps = deps_expression(
                variant_workspace + optional_external,
                "all_crate_deps(normal = True)",
            )
            if plan.target("build_script") is not None:
                variant_deps = deps_expression(
                    variant_workspace + optional_external + [":build_script"],
                    "all_crate_deps(normal = True)",
                )
            variant_attributes: dict[str, Any] = {
                "name": variant_name,
                "srcs": Raw('glob(["src/**/*.rs"])'),
                "crate_name": crate,
                "crate_root": relative_src_path(library, directory, root) if library else "src/lib.rs",
            }
            variant_target_sources = [
                source for source in sources
                if source.is_relative_to(root / directory / "src")
            ]
            variant_gated = feature_gated_sources(
                Path(str(library["src_path"])).resolve() if library else None,
                variant_target_sources,
                set(variant_features),
            )
            variant_target_sources = [
                source for source in variant_target_sources if source not in variant_gated
            ]
            variant_compile_data, _ = compile_data_labels(directory, variant_target_sources, root)
            variant_compile_data = sorted(
                set(variant_compile_data) | set(PACKAGE_EXTRA_COMPILE_DATA.get(directory, []))
            )
            if variant_compile_data:
                variant_attributes["compile_data"] = compile_data_expression(variant_compile_data)
            variant_attributes["crate_features"] = variant_features
            variant_attributes["edition"] = Raw("crate_edition()")
            variant_attributes["deps"] = Raw(variant_deps)
            variant_attributes["proc_macro_deps"] = Raw("all_crate_deps(proc_macro = True)")
            if plan.target(variant_name) is None:
                plan.targets.append(TargetPlan(
                    name=variant_name,
                    rule="rust_library",
                    attributes=variant_attributes,
                    cargo_target=f"{cargo_name} (feature variant)",
                    kinds=("lib",),
                ))
                used_names.add(variant_name)

        if "test" in kinds:
            target_name = assigned_names[cargo_name]
            binaries = cargo_bin_executables(cargo_target, assigned_names)
            test_deps = deps_expression(
                sorted(set(
                    [f":{variant_name}"] + normal_workspace + dev_workspace
                    + [f":{bazel_name}" for _, bazel_name in binaries]
                )),
                "all_crate_deps(normal = True, normal_dev = True)",
            )
            attributes = {
                "name": target_name,
                "crate_name": crate_name(cargo_name),
                "srcs": test_sources(cargo_target, directory, root),
            }
            if target_compile_data:
                attributes["compile_data"] = compile_data_expression(target_compile_data)
            if required:
                attributes["crate_features"] = sorted(set(features) | set(required))
            attributes["edition"] = Raw("crate_edition()")
            attributes["deps"] = Raw(test_deps)
            attributes["proc_macro_deps"] = Raw("all_crate_deps(proc_macro = True, proc_macro_dev = True)")
            if binaries:
                attributes["env"] = {
                    f"CARGO_BIN_EXE_{cargo_name}": f"$(execpath :{bazel_name})"
                    for cargo_name, bazel_name in binaries
                }
                attributes["rustc_env"] = {
                    f"CARGO_BIN_EXE_{cargo_name}": f"{directory}/{bazel_name}"
                    for cargo_name, bazel_name in binaries
                }
            plan.targets.append(TargetPlan(
                name=target_name,
                rule="rust_test",
                attributes=attributes,
                cargo_target=cargo_name,
                kinds=kinds,
            ))
            used_names.add(target_name)
        elif "bin" in kinds or "example" in kinds:
            target_name = assigned_names[cargo_name]
            # Cargo compiles examples with the dev-dependencies of the package,
            # but not binaries.
            normal_selector = (
                "all_crate_deps(normal = True, normal_dev = True)"
                if "example" in kinds
                else "all_crate_deps(normal = True)"
            )
            proc_macro_selector = (
                "all_crate_deps(proc_macro = True, proc_macro_dev = True)"
                if "example" in kinds
                else "all_crate_deps(proc_macro = True)"
            )
            binary_dependencies = list(normal_workspace)
            if plan.target(variant_name) is not None:
                binary_dependencies.append(f":{variant_name}")
            elif plan.target(library_name) is not None:
                # Cargo links a binary and an example against the library of
                # the same package.
                binary_dependencies.append(f":{library_name}")
            binary_dependencies = sorted(set(binary_dependencies))
            binary_deps = deps_expression(binary_dependencies, normal_selector)
            if plan.target("build_script") is not None:
                binary_deps = deps_expression(
                    binary_dependencies + [":build_script"], normal_selector
                )
            attributes = {
                "name": target_name,
                "srcs": binary_sources(cargo_target, directory, root),
                "crate_name": crate_name(cargo_name),
            }
            if target_compile_data:
                attributes["compile_data"] = compile_data_expression(target_compile_data)
            if features or required:
                attributes["crate_features"] = sorted(set(features) | set(required))
            attributes["edition"] = Raw("crate_edition()")
            attributes["deps"] = Raw(binary_deps)
            attributes["proc_macro_deps"] = Raw(proc_macro_selector)
            plan.targets.append(TargetPlan(
                name=target_name,
                rule="rust_binary",
                attributes=attributes,
                cargo_target=cargo_name,
                kinds=kinds,
            ))
            used_names.add(target_name)

            if has_unit_tests(binary_source_paths(cargo_target)):
                # Cargo compiles a binary target with the test harness, so the
                # unit tests of the binary run as part of `cargo test`.
                unit_test_name = f"{target_name}_test"
                unit_test_deps = deps_expression(
                    sorted(set(binary_dependencies + dev_workspace)),
                    "all_crate_deps(normal = True, normal_dev = True)",
                )
                unit_test_attributes: dict[str, Any] = {
                    "name": unit_test_name,
                    "srcs": binary_sources(cargo_target, directory, root),
                    "crate_name": f"{crate_name(cargo_name)}_test",
                    "crate_root": relative_src_path(cargo_target, directory, root),
                }
                if target_compile_data:
                    unit_test_attributes["compile_data"] = compile_data_expression(target_compile_data)
                if features or required:
                    unit_test_attributes["crate_features"] = sorted(set(features) | set(required))
                unit_test_attributes["edition"] = Raw("crate_edition()")
                unit_test_attributes["deps"] = Raw(unit_test_deps)
                unit_test_attributes["proc_macro_deps"] = Raw(
                    "all_crate_deps(proc_macro = True, proc_macro_dev = True)"
                )
                plan.targets.append(TargetPlan(
                    name=unit_test_name,
                    rule="rust_test",
                    attributes=unit_test_attributes,
                    cargo_target=f"{cargo_name} (unit tests)",
                    kinds=("bin",),
                ))
                used_names.add(unit_test_name)

    return plan


