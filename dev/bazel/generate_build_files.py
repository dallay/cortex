def starlark_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def starlark_value(value: Any) -> str:
    """Render a single Starlark value."""
    if isinstance(value, Raw):
        return str(value)
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return starlark_string(value)
    raise GeneratorError(f"unsupported Starlark value: {value!r}")


def starlark_list(values: list[Any], indent: str) -> str:
    rendered = ", ".join(starlark_value(value) for value in values)
    single_line = f"[{rendered}]"
    if len(indent) + len(single_line) + 1 <= 100:
        return single_line
    lines = ["["]
    for value in values:
        lines.append(f"{indent}    {starlark_value(value)},")
    lines.append(f"{indent}]")
    return "\n".join(lines)


def starlark_dict(values: dict[str, Any], indent: str) -> str:
    rendered = ", ".join(f"{starlark_string(key)}: {starlark_value(value)}" for key, value in values.items())
    single_line = f"{{{rendered}}}"
    if len(indent) + len(single_line) + 1 <= 100:
        return single_line
    lines = ["{"]
    for key, value in values.items():
        lines.append(f"{indent}    {key}: {value},")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def render_attribute(name: str, value: Any, indent: str) -> str:
    if isinstance(value, Raw):
        return f"{indent}{name} = {value},"
    if isinstance(value, str):
        return f"{indent}{name} = {starlark_string(value)},"
    if isinstance(value, bool):
        return f"{indent}{name} = {'True' if value else 'False'},"
    if isinstance(value, list):
        return f"{indent}{name} = {starlark_list(value, indent)},"
    if isinstance(value, dict):
        return f"{indent}{name} = {starlark_dict(value, indent)},"
    raise GeneratorError(f"unsupported attribute value for {name}: {value!r}")


def render_target(target_plan: TargetPlan) -> str:
    indent = "    "
    lines = [f"{target_plan.rule}("]
    for name, value in target_plan.attributes.items():
        lines.append(render_attribute(name, value, indent))
    lines.append(")")
    return "\n".join(lines)


def used_loads(plan: PackagePlan, body: str) -> list[str]:
    """Return the load statements required by the rendered body of a package."""
    rules = {target_plan.rule for target_plan in plan.targets}
    crates_symbols = [
        symbol for symbol in ("aliases", "all_crate_deps", "crate_edition")
        if f"{symbol}(" in body
    ]
    loads: list[tuple[str, list[str]]] = []
    if crates_symbols:
        loads.append(('"@crates//:defs.bzl"', crates_symbols))
    rust_symbols = sorted(rule for rule in rules if rule.startswith("rust_"))
    if rust_symbols:
        loads.append(('"@rules_rust//rust:defs.bzl"', rust_symbols))
    if "cargo_build_script" in rules:
        loads.append(('"@rules_rust//cargo:defs.bzl"', ["cargo_build_script"]))
    return loads


def render_package(plan: PackagePlan) -> str:
    """Render the BUILD file of a package plan."""
    body_lines: list[str] = []
    if plan.exports:
        body_lines.append("exports_files([")
        for export in plan.exports:
            body_lines.append(f"    {starlark_string(export)},")
        body_lines.append("])")
        body_lines.append("")
    for target_plan in plan.targets:
        body_lines.append(render_target(target_plan))
        body_lines.append("")
    body = "\n".join(body_lines)

    lines = [
        GENERATED_MARKER,
        "#",
        f"# Regenerate with: {REGENERATE_COMMAND}",
        f"# Verify with: {CHECK_COMMAND}",
        "#",
        "# The Cargo inventory is the source of truth. Do not edit this file by hand.",
        "",
    ]
    for module, symbols in used_loads(plan, body):
        lines.append(f"load({module}, {', '.join(starlark_string(symbol) for symbol in symbols)})")
    lines.append("")
    lines.append('package(default_visibility = ["//visibility:public"])')
    lines.append("")
    lines.append(body.rstrip("\n"))
    return "\n".join(lines).rstrip("\n") + "\n"


def parse_targets(text: str) -> dict[str, tuple[str, list[str]]]:
    """Parse the rule name and attribute names of every target in a BUILD file."""
    parsed: dict[str, tuple[str, list[str]]] = {}
    for match in RULE_RE.finditer(text):
        rule, body = match.group(1), match.group(2)
        name_match = NAME_RE.search(body)
        if not name_match:
            continue
        attributes = sorted(set(ATTRIBUTE_RE.findall(body)))
        parsed[name_match.group(1)] = (rule, attributes)
    return parsed


