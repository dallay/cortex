def inventory_sort_key(entry: dict[str, Any]) -> tuple[str, str, str, str]:
    return (
        str(entry.get("manifest", "")),
        str(entry.get("package_id", "")),
        str(entry.get("target", "")),
        str(entry.get("kinds", "")),
    )


def inventory_entries(plans: Any) -> list[dict[str, Any]]:
    """Return one inventory entry per Cargo target in the given plans."""
    if isinstance(plans, PackagePlan):
        plans = [plans]
    entries: list[dict[str, Any]] = []
    for plan in plans:
        for cargo_target in plan.package.get("targets", []):
            target_name = str(cargo_target["name"])
            kinds = target_kinds(cargo_target)
            identity_target = target_name
            matches = [
                target_plan for target_plan in plan.targets
                if target_plan.cargo_target == target_name and target_plan.kinds == kinds
            ]
            if matches:
                entry = {
                    "manifest": plan.manifest,
                    "package_id": plan.package_id,
                    "target": identity_target,
                    "kinds": ",".join(kinds),
                    "label": f"//{plan.directory}:{matches[0].name}",
                }
            else:
                reason = plan.exclusions.get(target_name) or TARGET_EXCLUSIONS.get((plan.directory, target_name))
                if not reason:
                    raise GeneratorError(
                        f"Cargo target has no Bazel target or reviewed exclusion: "
                        f"{plan.manifest}::{target_name} [{','.join(kinds)}]"
                    )
                entry = {
                    "manifest": plan.manifest,
                    "package_id": plan.package_id,
                    "target": identity_target,
                    "kinds": ",".join(kinds),
                    "exclusion": reason,
                }
            entries.append(entry)
    return sorted(entries, key=inventory_sort_key)


