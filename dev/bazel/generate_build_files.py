def package_source_files(directory: str, root: Path = ROOT) -> list[Path]:
    """Return the Rust sources of a package, sorted by path."""
    base = root / directory
    if not base.is_dir():
        return []
    files = [
        path
        for path in base.rglob("*.rs")
        if "bazel-" not in path.parts and "target" not in path.parts and ".git" not in path.parts
    ]
    return sorted(files)


def has_unit_tests(sources: list[Path]) -> bool:
    """Return True when a source file declares a `#[cfg(test)]` module."""
    for path in sources:
        try:
            content = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        if CFG_TEST_RE.search(content):
            return True
    return False


def sandbox_tags_for(directory: str, target_name: str) -> list[str]:
    """Return the Bazel tags a target needs to run outside the sandbox."""
    if (directory, target_name) in NO_SANDBOX_TARGETS:
        return ["no-sandbox"]
    return []


def evaluate_cfg_expression(expr: str, enabled: set[str]) -> bool | None:
    """Evaluate a Rust cfg(...) expression against enabled Cargo features.

    Returns True if satisfied, False if not satisfied, or None if ambiguous/unknown.
    When ambiguous, the conservative choice is not to exclude sources.
    """
    expr = expr.strip()
    if expr.startswith("#[") and expr.endswith("]"):
        expr = expr[2:-1].strip()
    if expr.startswith("cfg(") and expr.endswith(")"):
        expr = expr[4:-1].strip()

    def split_args(s: str) -> list[str]:
        args: list[str] = []
        depth = 0
        current: list[str] = []
        for char in s:
            if char in "([":
                depth += 1
            elif char in ")]":
                depth -= 1
            elif char == "," and depth == 0:
                arg = "".join(current).strip()
                if arg:
                    args.append(arg)
                current = []
                continue
            current.append(char)
        last = "".join(current).strip()
        if last:
            args.append(last)
        return args

    def evaluate(s: str) -> bool | None:
        s = s.strip()
        m = FEATURE_ATTRIBUTE_RE.fullmatch(s)
        if m:
            return m.group(1) in enabled
        if s.startswith("all(") and s.endswith(")"):
            results = [evaluate(p) for p in split_args(s[4:-1])]
            if any(r is False for r in results):
                return False
            if all(r is True for r in results):
                return True
            return None
        if s.startswith("any(") and s.endswith(")"):
            results = [evaluate(p) for p in split_args(s[4:-1])]
            if any(r is True for r in results):
                return True
            if all(r is False for r in results):
                return False
            return None
        if s.startswith("not(") and s.endswith(")"):
            res = evaluate(s[4:-1])
            return not res if res is not None else None
        return None

    return evaluate(expr)


def feature_gated_sources(
    crate_root: Path | None,
    sources: list[Path],
    enabled: set[str],
) -> set[Path]:
    """Return the sources that a disabled Cargo feature keeps out of the build.

    A module declared behind `#[cfg(feature = "...")]` is not compiled when the
    feature is off, so the files it embeds are not compile inputs either.
    Composite predicates (`any`, `all`, `not`) are evaluated; if the outcome is
    ambiguous or unknown, the conservative default is not to exclude the source.
    """
    if crate_root is None or not crate_root.is_file():
        return set()
    try:
        content = crate_root.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return set()
    excluded: set[Path] = set()
    pending: list[str] = []
    attribute_lines: list[str] = []
    for line in content.splitlines():
        stripped = line.strip()
        if stripped.startswith("#[") or attribute_lines:
            attribute_lines.append(stripped)
            if not stripped.endswith("]"):
                continue
            pending.append(" ".join(attribute_lines))
            attribute_lines = []
            continue
        attribute_lines = []
        match = MODULE_DECLARATION_RE.match(stripped)
        if match is None:
            pending = []
            continue
        module = match.group("module")
        # Each cfg attribute is conjunctive; one false predicate disables the module.
        # Unknown predicates do not exclude sources from compile_data.
        is_gated = any(evaluate_cfg_expression(attr, enabled) is False for attr in pending)
        if is_gated:
            for source in sources:
                if source.parent.name == module or source.stem == module:
                    excluded.add(source)
        pending = []
    return excluded


def binary_source_paths(cargo_target: dict[str, Any]) -> list[Path]:
    """Return the source files of a binary or example target."""
    entry = Path(str(cargo_target["src_path"])).resolve()
    sources = [entry]
    sources.extend(module_sources(entry))
    return sorted(set(sources))


def binary_sources(cargo_target: dict[str, Any], directory: str, root: Path = ROOT) -> list[str]:
    """Return the package relative sources of a binary or example target."""
    relative: list[str] = []
    for source in binary_source_paths(cargo_target):
        inside = relative_to_package(source, directory, root)
        if inside is not None:
            relative.append(inside)
    return sorted(set(relative))


def test_sources(cargo_target: dict[str, Any], directory: str, root: Path = ROOT) -> list[str]:
    """Return the sources of an integration test target.

    A Rust file may pull in a module from another crate with a relative
    `#[path]` attribute. Bazel only sees files that its own package declares, so
    a module that a nearer package owns is addressed by label instead of by a
    path that would escape the package.
    """
    entry = Path(str(cargo_target["src_path"])).resolve()
    sources = [entry]
    sources.extend(module_sources(entry))
    resolved: list[str] = []
    for source in sources:
        inside = relative_to_package(source, directory, root)
        if inside is not None:
            resolved.append(inside)
            continue
        label = cross_package_label(source, root)
        if label is not None:
            resolved.append(label)
    return sorted(set(resolved))


def cross_package_label(path: Path, root: Path = ROOT) -> str | None:
    """Return the Bazel label of a source that another package owns.

    The owning package must export the file. `None` means the source is outside
    the repository, which no label can address.
    """
    root = root.resolve()
    path = path.resolve()
    if root not in path.parents:
        return None
    owner = owning_package_directory(path, root)
    if not owner:
        return f"//:{path.relative_to(root).as_posix()}"
    return f"//{owner}:{path.relative_to(root / owner).as_posix()}"


def module_sources(path: Path) -> list[Path]:
    """Return the module files a Rust source file pulls in with `mod x;`.

    Cargo compiles an integration test with the `tests` directory as its
    module root, so `mod common;` resolves to `tests/common.rs` or
    `tests/common/mod.rs`. Bazel needs those files listed as sources.
    """
    try:
        content = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return []
    found: list[Path] = []
    for match in MODULE_DECLARATION_RE.finditer(content):
        module = match.group("module")
        for candidate in (path.parent / f"{module}.rs", path.parent / module / "mod.rs"):
            if candidate.is_file():
                found.append(candidate)
                found.extend(module_sources(candidate))
                break
    for match in PATH_ATTRIBUTE_RE.finditer(content):
        candidate = (path.parent / match.group("path")).resolve()
        if candidate.is_file():
            found.append(candidate)
            found.extend(module_sources(candidate))
    return found


def compile_data_expression(items: list[Any]) -> Raw:
    """Return the Starlark expression for a compile data attribute.

    Bazel expects a flat list of files, so the glob results and the plain
    files are combined with a list concatenation.
    """
    patterns: list[str] = []
    files: list[str] = []
    for item in items:
        match = GLOB_EXPRESSION_RE.match(str(item))
        if match:
            patterns.append(match.group("pattern"))
        else:
            files.append(str(item))
    parts: list[str] = []
    if patterns:
        rendered = ", ".join(starlark_string(pattern) for pattern in sorted(set(patterns)))
        parts.append(f"glob([{rendered}])")
    if files:
        rendered = ", ".join(starlark_string(name) for name in sorted(set(files)))
        parts.append(f"[{rendered}]")
    if not parts:
        return Raw("[]")
    return Raw(" + ".join(parts))


def cargo_bin_executables(
    cargo_target: dict[str, Any],
    assigned_names: dict[str, str],
) -> list[tuple[str, str]]:
    """Return the Cargo binaries a test target refers to through `CARGO_BIN_EXE`.

    Cargo exposes the path of a package binary to integration tests through the
    `CARGO_BIN_EXE_<name>` environment variable. The generator reproduces that
    contract with the runfiles path of the Bazel binary target. The variable can
    be read from any module of the test crate, not only from the entry file, so
    every source of the target is scanned.
    """
    entry = Path(str(cargo_target["src_path"]))
    contents: list[str] = []
    for source in [entry, *module_sources(entry)]:
        try:
            contents.append(source.read_text(encoding="utf-8", errors="ignore"))
        except OSError:
            continue
    binaries: list[tuple[str, str]] = []
    for cargo_name in sorted(set(CARGO_BIN_EXE_RE.findall("\n".join(contents)))):
        bazel_name = assigned_names.get(cargo_name)
        if bazel_name is None:
            continue
        binaries.append((cargo_name, bazel_name))
    return binaries


def owning_package_directory(path: Path, root: Path = ROOT) -> str:
    """Return the Bazel package that owns a file, using the nearest BUILD file."""
    current = path.parent
    while True:
        if (current / "BUILD.bazel").is_file() or (current / "BUILD").is_file():
            try:
                return current.relative_to(root).as_posix()
            except ValueError:
                return ""
        if current == root:
            return ""
        if root not in current.parents:
            return ""
        current = current.parent


def referenced_files(sources: list[Path], root: Path = ROOT) -> list[tuple[Path, Path]]:
    """Return the (including file, referenced file) pairs found in the sources."""
    references: list[tuple[Path, Path]] = []
    for path in sources:
        try:
            content = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for match in INCLUDE_FILE_RE.finditer(content):
            target = (path.parent / match.group(1)).resolve()
            references.append((path, target))
    return references


def embedded_migration_directories(sources: list[Path]) -> list[str]:
    """Return the migration directories embedded by refinery style macros."""
    directories: set[str] = set()
    for path in sources:
        try:
            content = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for match in EMBED_MIGRATIONS_RE.finditer(content):
            directories.add(match.group(1))
    return sorted(directories)


def rust_embed_folders(sources: list[Path]) -> list[str]:
    """Return the folders embedded by `rust-embed` derives."""
    folders: set[str] = set()
    for path in sources:
        try:
            content = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for match in RUST_EMBED_FOLDER_RE.finditer(content):
            folders.add(match.group(1))
    return sorted(folders)


def relative_to_package(path: Path, directory: str, root: Path = ROOT) -> str | None:
    """Return the package relative POSIX path of a file, or None when outside."""
    try:
        return path.resolve().relative_to((root / directory).resolve()).as_posix()
    except ValueError:
        return None


def glob_matches(pattern: str, path: str) -> bool:
    """Return True when a workspace relative path matches a Bazel glob pattern."""
    parts = pattern.split("/")
    expression = ""
    for index, part in enumerate(parts):
        if part == "**":
            expression += "(?:.*/)?" if index < len(parts) - 1 else ".*"
            continue
        chunk = ""
        for character in part:
            if character == "*":
                chunk += "[^/]*"
            elif character == "?":
                chunk += "[^/]"
            else:
                chunk += re.escape(character)
        expression += chunk
        if index < len(parts) - 1:
            expression += "/"
    return re.fullmatch(expression, path) is not None


def root_package_exports(relative_path: str, root: Path = ROOT) -> bool:
    """Return True when the root BUILD file exports a root package file.

    The root package owns every file that has no nearer BUILD file. A crate can
    only reach such a file when the root package exports it.
    """
    build_file = root / "BUILD.bazel"
    if not build_file.is_file():
        return False
    content = build_file.read_text(encoding="utf-8", errors="ignore")
    patterns: list[str] = []
    for match in EXPORTS_FILES_RE.finditer(content):
        arguments = match.group(1)
        glob_match = GLOB_ARGUMENT_RE.search(arguments)
        if glob_match is not None:
            patterns.extend(GLOB_PATTERN_RE.findall(glob_match.group(1)))
            continue
        patterns.extend(STRING_LITERAL_RE.findall(arguments))
    return any(glob_matches(pattern, relative_path) for pattern in patterns)


def compile_data_labels(
    plan_directory: str,
    sources: list[Path],
    root: Path = ROOT,
) -> tuple[list[str], list[str]]:
    """Return the compile data labels of a package and the files needing export.

    The first element holds labels usable as `compile_data`. The second holds
    absolute paths that live in another package and therefore need an export
    from that package.
    """
    labels: list[str] = []
    foreign: list[str] = []
    for _, target in referenced_files(sources, root):
        inside = relative_to_package(target, plan_directory, root)
        if inside is not None:
            labels.append(inside)
            continue
        owner = owning_package_directory(target, root)
        try:
            relative = target.resolve().relative_to(root.resolve()).as_posix()
        except ValueError:
            foreign.append(str(target))
            continue
        if not owner or owner == ".":
            # The root package owns the file. It is reachable when the root
            # BUILD file exports it, and unreachable otherwise.
            if root_package_exports(relative, root):
                labels.append(f"//:{relative}")
                continue
            foreign.append(str(target))
            continue
        file_part = target.resolve().relative_to((root / owner).resolve()).as_posix()
        labels.append(f"//{owner}:{file_part}")
        foreign.append(str(target))
    for migration_directory in embedded_migration_directories(sources):
        labels.append(Raw(f'glob(["{migration_directory}/**"])'))
    for folder in rust_embed_folders(sources):
        if is_separate_package(folder, plan_directory, root):
            # The folder belongs to another Bazel package, so the filegroup of
            # that package carries the assets.
            continue
        labels.append(Raw(f'glob(["{folder}/**"])'))
    return sorted(set(labels)), sorted(set(foreign))


def is_separate_package(path: str, plan_directory: str, root: Path = ROOT) -> bool:
    """Return True when the package relative path lives in another package."""
    package_root = (root / plan_directory).resolve()
    current = (package_root / path).resolve()
    while current != package_root:
        if (current / "BUILD.bazel").is_file() or (current / "BUILD").is_file():
            return True
        if current == current.parent:
            return False
        current = current.parent
    return False


