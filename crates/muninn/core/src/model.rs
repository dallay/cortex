impl Preference {
    /// Igualdad textual: las mayúsculas y los espacios no cambian el valor.
    pub fn equivalent_value(&self, value: &str) -> bool {
        fn normalize(text: &str) -> String {
            text.split_whitespace()
                .collect::<Vec<_>>()
                .join(" ")
                .to_lowercase()
        }
        normalize(&self.preference) == normalize(value)
    }
}

